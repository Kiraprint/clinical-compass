/**
 * Подсказка дозировки из справочника ГРЛС (FR-32) для формы назначения.
 *
 * Частота приёма в форме — отдельное поле («сколько раз в день», 1..6), и её
 * значение приходит с бэкенда структурно (`Drug.times_per_day`). Текст
 * инструкции при этом содержит ту же частоту словами («2 раза/сут»,
 * «1 раз в день»): если подставить его в поле дозировки целиком, врач получает
 * режим дважды — свободным текстом и в select. Поэтому из подставляемого текста
 * вырезаем только частотное уточнение, остальное (доза, титрация, длительность)
 * оставляем дословно: инструкцию не переписываем.
 */

/** «2 раза/сут», «1 раз в день», «1-2 раза в день», «3 раза в сутки», «2 р./сут». */
const FREQUENCY_CLAUSE =
  /(?<![\d.,])\d{1,2}(?:\s*[-–—]\s*\d{1,2})?\s*(?:раз(?:а)?|р\.?)\s*(?:\/\s*|\s+в\s+)(?:сут\p{L}*|день|дня|дней|дн)(?!\p{L})/giu;

/** Метка вырезанного оборота: по ней видно, где стоял союз, и что он осиротел. */
const CUT = "\u0000";

/**
 * Убирает частотные обороты и чинит пунктуацию/пробелы на месте вырезанного.
 * Когда после вырезанного оборота остаётся союз («1 раз/сут или 2 раза/сут»,
 * «2 раза/сут или по назначению»), союз тоже уходит: он связывал именно
 * частоты, и без них фраза рассыпается («или по 20 мг»).
 */
export function stripIntakeFrequency(text: string): string {
  if (!text) return "";
  const cut = text
    .replace(FREQUENCY_CLAUSE, CUT)
    .replace(/[\u0000]\s*(?:или|либо)\s*[\u0000]/giu, CUT) // «[M] или [M]» → «[M]»
    .replace(/[\u0000]\s*(?:или|либо)\s+/giu, "") // «[M] или по 20 мг» → «по 20 мг»
    .replace(/\s+(?:или|либо)\s*[\u0000]/giu, ""); // «20 мг или [M]» → «20 мг»
  return (
    cut
      .replace(/\u0000/g, " ")
      .replace(/\(\s*\)/g, " ") // «(2 раза/сут)» не оставляет пустых скобок
      .replace(/[ \t\u00a0]{2,}/g, " ")
      .replace(/([,;:])\s*(?=[,;:])/g, "") // «мг, , внутрь» → «мг, внутрь»
      .replace(/\s+([,.;:!?])/g, "$1") // «мг .» → «мг.»
      .replace(/([,;:])\s*(?=[.;!?]|$)/g, "") // «мг, .» → «мг.»
      .replace(/([,.;:!?])(?:\s*\1)+/g, "$1") // «Внутрь..» → «Внутрь.»
      .replace(/^[\s,;:.]+/, "") // «, внутрь» → «внутрь»
      .trim()
  );
}

/**
 * Что показать в select «раз в день» при выборе препарата.
 *
 * `null` из справочника (частоты нет, она неоднозначна или вне 1..6) — это
 * 1, а не «оставить прошлое значение»: текст препарата уже очищен от частоты,
 * и унаследованный знаменатель приверженности относился бы к другому препарату.
 */
export function resolveTimesPerDay(drug: { times_per_day: number | null }): number {
  return drug.times_per_day ?? 1;
}
