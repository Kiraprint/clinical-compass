/**
 * Кратность приёма в форме назначения (FR-23/FR-27).
 *
 * Инструкция ГРЛС обычно уже содержит суточную кратность («Внутрь по 20 мг
 * 2 раза/сут»). Если она есть в тексте дозировки, отдельный селект «Раз в день»
 * избыточен: врач уже написал режим, и заставлять его выбирать число второй раз
 * — лишний шаг и повод разойтись с текстом. Поэтому кратность читается из поля
 * дозировки, а селект показывается только когда в тексте её нет.
 *
 * Парсер — зеркало бэкенда `app.services.drug_dosage.parse_times_per_day`
 * (API отдаёт `Drug.times_per_day` тем же правилом): правила должны совпадать,
 * иначе скрытый селект и сохранённое значение разъедутся.
 */

/** «2 раза/сут», «1 раз в день», «1-2 раза в день», «3 раза в сутки», «2 р./сут». */
const INTAKE_FREQUENCY =
  /(?<![\d.,])(\d{1,2})(?:\s*[-–—]\s*(\d{1,2}))?\s*(?:раз(?:а)?|р\.?)\s*(?:\/\s*|\s+в\s+)(?:сут\p{L}*|день|дня|дней|дн)(?!\p{L})/giu;

/**
 * Кратность из текста дозировки; `null` — её нет или она неоднозначна.
 *
 * Консервативно, как на бэкенде: диапазон «1-2 раза в день» → нижняя граница 1
 * (приверженность не должна требовать больше приёмов, чем назначено минимум),
 * разные кратности в одном тексте и значения вне 1..6 (диапазон селекта) → null.
 * Дозовые записи «50 мг/сут» кратностью не считаются: слова «раз» нет.
 */
export function parseIntakeFrequency(text: string): number | null {
  if (!text) return null;
  const values = new Set<number>();
  for (const match of text.matchAll(INTAKE_FREQUENCY)) {
    const low = Number(match[1]);
    const high = match[2] ? Number(match[2]) : null;
    values.add(high == null ? low : Math.min(low, high));
  }
  if (values.size !== 1) return null;
  const times = [...values][0];
  return times >= 1 && times <= 6 ? times : null;
}

/** «Из дозировки: 2 раза в день» — русские формы для 1..6. */
export function formatTimesPerDay(times: number): string {
  const word = times === 1 || times >= 5 ? "раз" : "раза";
  return `${times} ${word} в день`;
}

/**
 * Что показать в select «раз в день» при выборе препарата, пока дозировка ещё
 * не подставлена. `null` из справочника — это 1, а не значение прошлого
 * препарата: унаследованный знаменатель приверженности относился бы к другому
 * препарату.
 */
export function resolveTimesPerDay(drug: { times_per_day: number | null }): number {
  return drug.times_per_day ?? 1;
}

/**
 * Расхождение сохранённого режима с кратностью из текста дозировки.
 *
 * В колонке «Режим» показывается `PatientMedication.times_per_day` — именно по
 * нему считается приверженность (FR-27), а не по тексту дозировки. Если числа
 * разошлись (назначение создано до того, как форма начала брать кратность из
 * текста), врач должен видеть оба и привести сохранённое к дозировке. `null` —
 * расхождения нет либо кратности в тексте нет, править нечего.
 */
export function describeRegimeMismatch(stored: number | null, derived: number | null): string | null {
  if (derived == null || derived === stored) return null;
  return `в дозировке ${derived}, сохранено ${stored ?? "—"}`;
}
