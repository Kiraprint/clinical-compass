/**
 * Подсказка дозировки из справочника ГРЛС (FR-32) для формы назначения.
 *
 * Частота приёма в форме — отдельное поле («сколько раз в день», 1..6), и её
 * значение приходит с бэкенда структурно (`Drug.times_per_day`). Текст
 * инструкции при этом содержит ту же частоту словами («2 раза/сут»,
 * «1 раз в день»): если подставить его в поле дозировки целиком, врач получает
 * режим дважды — свободным текстом и в select. Поэтому из подставляемого текста
 * вырезаем только частотное уточнение, остальное (доза, титрация, длительность)
 * оставляем дословно: инструкцию не переписываем.
 */

/** «2 раза/сут», «1 раз в день», «1-2 раза в день», «3 раза в сутки», «2 р./сут». */
const FREQUENCY_CLAUSE =
  /(?<![\d.,])\d{1,2}(?:\s*[-–—]\s*\d{1,2})?\s*(?:раз(?:а)?|р\.?)\s*(?:\/\s*|\s+в\s+)(?:сут\p{L}*|день|дня|дней|дн)(?!\p{L})/giu;

/** Убирает частотные обороты и чинит пунктуацию/пробелы на месте вырезанного. */
export function stripIntakeFrequency(text: string): string {
  if (!text) return "";
  return text
    .replace(FREQUENCY_CLAUSE, " ")
    .replace(/\(\s*\)/g, " ") // «(2 раза/сут)» не оставляет пустых скобок
    .replace(/[ \t\u00a0]{2,}/g, " ")
    .replace(/([,;:])\s*(?=[,;:])/g, "") // «мг, , внутрь» → «мг, внутрь»
    .replace(/\s+([,.;:!?])/g, "$1") // «мг .» → «мг.»
    .replace(/([,;:])\s*(?=[.;!?]|$)/g, "") // «мг, .» → «мг.»
    .replace(/^[\s,;:]+/, "") // «, внутрь» → «внутрь»
    .trim();
}
