export type LegalPage = "terms" | "consent";

/** `/legal/terms` | `/legal/consent` → страница; иначе null (обычное приложение). */
export function legalPageFromPath(path: string): LegalPage | null {
  const p = path.replace(/\/+$/, "").toLowerCase();
  if (p === "/legal/terms") return "terms";
  if (p === "/legal/consent") return "consent";
  return null;
}

