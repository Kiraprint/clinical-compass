"""Разбор частоты приёма из текста инструкции ГРЛС (`drugs.dosage`).

Частота приёма — часть режима дозирования, а не свободный текст: в форме
назначения врач задаёт её отдельным полем «сколько раз в день» (1..6), и
знаменатель приверженности (FR-27) считается именно по нему. Поэтому разбор
живёт на бэкенде рядом с данными справочника: клиенты получают готовое
`times_per_day` и не дублируют клинический парсинг каждый по-своему.

Правила разбора (консервативные, лучше null, чем неверное число):

* распознаются только явные конструкции «N раз(а) в сутки/день» и «N раз/сут»,
  в том числе сокращение «N р./сут»; дозовые записи вида «50 мг/сут» частотой
  не считаются (нет слова «раз»);
* диапазон «1-2 раза в день» даёт нижнюю границу (1): знаменатель приверженности
  не должен требовать от пациента больше приёмов, чем назначено минимум;
* разные частоты в одном тексте (разные показания/схемы) — неоднозначно, null;
* значение вне диапазона формы (1..6) не подставляется (null), а не «зажимается»:
  подстановка 6 вместо назначенных 8 исказила бы инструкцию.
"""
from __future__ import annotations

import re

__all__ = ["parse_times_per_day"]

MIN_TIMES_PER_DAY = 1
MAX_TIMES_PER_DAY = 6

# «2 раза/сут», «1 раз в день», «1-2 раза в день», «3 раза в сутки», «2 р./сут».
# (?<![\d.,]) — чтобы «20 мг» и «1,5» не начинали совпадение с середины числа.
_FREQUENCY_CLAUSE = re.compile(
    r"(?<![\d.,])(?P<low>\d{1,2})(?:\s*[-–—]\s*(?P<high>\d{1,2}))?"
    r"\s*(?:раз(?:а)?|р\.?)"
    r"\s*(?:/\s*|\s+в\s+)"
    r"(?:сут\w*|день|дня|дней|дн)(?!\w)",
    re.IGNORECASE,
)


def _clause_value(match: re.Match[str]) -> int:
    low = int(match.group("low"))
    high = match.group("high")
    # Диапазон → нижняя граница (см. docstring), перевёрнутый диапазон тоже.
    return min(low, int(high)) if high else low


def parse_times_per_day(dosage: str | None) -> int | None:
    """Число приёмов в сутки из текста инструкции или None, если не определить."""
    if not dosage:
        return None
    values = {_clause_value(m) for m in _FREQUENCY_CLAUSE.finditer(dosage)}
    if len(values) != 1:
        return None  # пусто — частоты нет; несколько разных — неоднозначно
    times = values.pop()
    if not MIN_TIMES_PER_DAY <= times <= MAX_TIMES_PER_DAY:
        return None
    return times
